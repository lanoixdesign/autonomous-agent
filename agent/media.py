"""Minimal interfaces for non-chat categories (image, audio_tts, audio_stt, embeddings...).

They only route the KEY: `KeyedService.run(call, ...)` reserves a request on the best key of the
category (limits checked and reserved, failover on 429 / 5xx), calls `call(lease, ...)` with
`lease.api_key`, `lease.base_url` and `lease.model`, then records the usage. Plug the real provider
call in `call`; nothing is generated by this module itself.

    images = ImageGenerator(router)
    png = images.generate("a red bicycle", call=my_openai_images_call)   # my_call(lease, prompt, size)
"""
from __future__ import annotations

from typing import Any, Callable

from .keys import KeyRouter, KeysExhausted, Lease


class ProviderError(Exception):
    """Raise this from a `call` with the HTTP status so 429 / 5xx fail over to the next key."""

    def __init__(self, message: str, status: int | None = None, retry_after: float | None = None):
        super().__init__(message)
        self.status, self.retry_after = status, retry_after


class KeyedService:
    category = ""

    def __init__(self, router: KeyRouter, category: str | None = None):
        self.router = router
        self.category = category or self.category

    def run(self, call: Callable[..., Any] | None, *args: Any, images: float = 0, audio_minutes: float = 0,
            prompt_tokens: int = 0, **kw: Any) -> Any:
        if call is None:
            raise NotImplementedError(f"no provider call plugged in for category '{self.category}'")
        errors = []
        while True:
            try:
                lease: Lease = self.router.acquire(self.category, prompt_tokens=prompt_tokens,
                                                   images=images, audio_minutes=audio_minutes)
            except KeysExhausted as e:
                if errors:
                    raise KeysExhausted(e.category, {**e.reasons, "errors": " | ".join(errors)})
                raise
            try:
                out = call(lease, *args, **kw)
            except ProviderError as e:
                lease.fail(e.status, e.retry_after)
                if e.status is not None and e.status != 429 and e.status < 500:
                    raise
                errors.append(f"{lease.name}: {e}")
                continue
            except Exception:
                lease.fail(None)
                raise
            lease.commit(prompt_tokens=prompt_tokens, images=images, audio_minutes=audio_minutes)
            return out


class ImageGenerator(KeyedService):
    category = "image"

    def generate(self, prompt: str, size: str = "1024x1024", n: int = 1, call: Callable[..., Any] | None = None) -> Any:
        return self.run(call, prompt, size, n, images=n)


class TextToSpeech(KeyedService):
    category = "audio_tts"

    def speak(self, text: str, minutes: float, call: Callable[..., Any] | None = None) -> Any:
        return self.run(call, text, audio_minutes=minutes)


class SpeechToText(KeyedService):
    category = "audio_stt"

    def transcribe(self, path: str, minutes: float, call: Callable[..., Any] | None = None) -> Any:
        return self.run(call, path, audio_minutes=minutes)


class Embeddings(KeyedService):
    category = "embeddings"

    def embed(self, texts: list[str], call: Callable[..., Any] | None = None) -> Any:
        return self.run(call, texts, prompt_tokens=sum(len(t) for t in texts) // 3 + 1)
