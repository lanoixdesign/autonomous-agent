STRINGS = {"en": EN, "fr": FR}
PLACEHOLDER_RE = re.compile(r"\{(\w+)[^}]*\}")


def normalize(lang: str | None) -> str:
    """'fr', 'fr-FR', 'FR_ca' -> 'fr'; anything else -> 'en'."""
    return "fr" if str(lang or "").strip().lower().startswith("fr") else DEFAULT


def env_lang() -> str:
    return normalize(os.environ.get("AGENT_LANG"))


def t(lang: str, key: str, **kw) -> str:
    s = STRINGS[normalize(lang)].get(key) or EN.get(key) or key
    return s.format(**kw) if kw else s


def ui_strings() -> dict[str, dict[str, str]]:
    """What the pages get: everything except the terminal and export strings."""
    return {lang: {k: v for k, v in d.items() if not k.startswith(("cli.", "export.", "desktop."))}
            for lang, d in STRINGS.items()}
