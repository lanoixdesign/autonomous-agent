"""Draws the app logo (assets/icon.svg) and writes every icon file from it.

    pip install cairosvg pillow && python packaging/make_icons.py

Logo: the app's mark (a ring around a rounded square, as on the welcome page and the download site), white on
the app's muted blue. Two shapes: full-bleed (Windows, favicons, PWA) and the macOS grid (824/1024 squircle with margin).
The outputs are committed, so the build itself needs neither cairosvg nor Pillow.
"""
import base64
import io
import os

import cairosvg
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
A = os.path.join(ROOT, "assets")

BODY = """<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
<stop offset="0" stop-color="#4B6699"/><stop offset="1" stop-color="#33497A"/></linearGradient></defs>
<rect width="1024" height="1024" rx="232" fill="url(#bg)"/>
<circle cx="512" cy="512" r="292" fill="none" stroke="#F3F5FA" stroke-width="88"/>
<rect x="382" y="382" width="260" height="260" rx="72" fill="#F3F5FA"/>"""

FULL = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">' + BODY + '</svg>'
# macOS: the artwork sits in an 824 px rounded square centred on the 1024 canvas (Apple's icon grid).
MAC = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><g transform="translate(100 100) '
       'scale(0.8046875)">' + BODY.replace('rx="232"', 'rx="225"') + '</g></svg>')


def png(svg, size):
    return Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg.encode(), output_width=size,
                                                  output_height=size))).convert("RGBA")


def main():
    os.makedirs(A, exist_ok=True)
    open(os.path.join(A, "icon.svg"), "w").write(FULL + "\n")
    open(os.path.join(A, "icon-macos.svg"), "w").write(MAC + "\n")
    png(FULL, 1024).save(os.path.join(A, "icon.png"))
    big = png(MAC, 1024)
    big.save(os.path.join(A, "icon-macos.png"))
    big.save(os.path.join(A, "icon.icns"), sizes=[(16, 16), (32, 32), (64, 64), (128, 128), (256, 256),
                                                 (512, 512), (1024, 1024)])
    # Windows .ico: each size rendered from the vector (sharper than one downscale).
    sizes = [16, 24, 32, 48, 64, 128, 256]
    ims = [png(FULL, s) for s in sizes]
    ims[-1].save(os.path.join(A, "icon.ico"), sizes=[(s, s) for s in sizes], append_images=ims[:-1])
    # Web UI icons (agent/icon_data.py, pure stdlib at run time).
    out = ['"""App logo for the web pages (generated by packaging/make_icons.py; do not edit)."""',
           "SVG = " + repr(FULL.encode())]
    for s in (32, 180, 192, 512):
        b = io.BytesIO()
        png(FULL, s).save(b, "PNG", optimize=True)
        out.append(f"PNG_{s} = " + repr(base64.b64encode(b.getvalue()).decode()))
    open(os.path.join(ROOT, "agent", "icon_data.py"), "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
